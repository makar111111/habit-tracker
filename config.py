"""Налаштування, які беруться з оточення, а не з коду.

Правило просте: усе, що відрізняється між твоїм комп'ютером і сервером
(адреси, паролі, токени), не має бути записане прямо в коді. Інакше
секрет поїде в git, а щоб змінити адресу на сервері, доведеться правити код.
"""

import os

from dotenv import load_dotenv

# Читає файл .env і кладе його рядки в змінні оточення.
# Якщо файлу немає — мовчки нічого не робить, і працюють значення за
# замовчуванням нижче. Тому проєкт запускається одразу після клонування.
load_dotenv()


# Пароль, яким бот доводить API, що він — це справді він.
# Порожній рядок означає "бот не налаштований": доступ ботові буде закрито.
BOT_SECRET = os.environ.get("BOT_SECRET", "")

# Токен від @BotFather. Використає бот на кроці 2.
BOT_TOKEN = os.environ.get("BOT_TOKEN", "")

# Де бот шукатиме API.
API_URL = os.environ.get("API_URL", "http://127.0.0.1:8000")
