"""Налаштування, які беруться з оточення, а не з коду.

Правило просте: усе, що відрізняється між твоїм комп'ютером і сервером
(адреси, паролі, токени), не має бути записане прямо в коді. Інакше
секрет поїде в git, а щоб змінити адресу на сервері, доведеться правити код.
"""

import os

from dotenv import load_dotenv

# Читає файл .env і кладе його рядки в змінні оточення.
# Якщо файлу немає — мовчки нічого не робить, і працюють значення за
# замовчуванням нижче. Тому проєкт запускається одразу після клонування.
load_dotenv()


# Пароль, яким бот доводить API, що він — це справді він.
# Порожній рядок означає "бот не налаштований": доступ ботові буде закрито.
BOT_SECRET = os.environ.get("BOT_SECRET", "")

# Токен від @BotFather.
BOT_TOKEN = os.environ.get("BOT_TOKEN", "")

# Де бот шукатиме API.
API_URL = os.environ.get("API_URL", "http://127.0.0.1:8000")

# Сумісність зі старим helper next_run_at. Робочий цикл нагадувань бере
# особисті reminder_hour і timezone користувача з API.
REMINDER_HOUR = int(os.environ.get("REMINDER_HOUR", "20"))

# Де лежить база. Три слеші — це "файл за відносним шляхом", тобто
# habits.db у поточній теці.
#
# Налаштовується ззовні заради контейнерів: усередині Docker база має
# лежати на змонтованому томі (наприклад, sqlite:////data/habits.db —
# чотири слеші, бо шлях абсолютний), інакше вона зникне разом
# із контейнером при першому ж перезапуску.
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip() or "sqlite:///habits.db"

# Ім'я бота без @ — з нього збирається посилання для входу
# (t.me/ІМ'Я?start=КОД). API не може дізнатись його сам: бот знає своє
# ім'я через get_me(), а сервер із Telegram не спілкується взагалі.
BOT_USERNAME = os.environ.get("BOT_USERNAME", "")

# Чим підписуються cookie сесій. Порожній рядок = вхід у веб вимкнено:
# без секрету підпис не має сенсу, а підробити cookie зміг би будь-хто.
SESSION_SECRET = os.environ.get("SESSION_SECRET", "")

# Скільки живе сесія у браузері. 30 днів — компроміс: трекер звичок
# відкривають раз на день, і вимагати вхід щоразу було б знущанням.
SESSION_TTL_SECONDS = int(os.environ.get("SESSION_TTL_SECONDS", 30 * 24 * 3600))

# Скільки живе код входу. Мало навмисно: код — це фактично пароль,
# і в нього не має бути часу «полежати» в історії браузера чи в чаті.
LOGIN_TOKEN_TTL_SECONDS = int(os.environ.get("LOGIN_TOKEN_TTL_SECONDS", 300))

# Скільки кодів входу одна IP-адреса може попросити за вікно. Людині
# вистачає одного-двох (відкрила сторінку, може, оновила); десять за
# хвилину — з запасом для живої людини і замало для флуду бази.
LOGIN_CODE_RATE_LIMIT = int(os.environ.get("LOGIN_CODE_RATE_LIMIT", 10))
LOGIN_CODE_RATE_WINDOW_SECONDS = int(
    os.environ.get("LOGIN_CODE_RATE_WINDOW_SECONDS", 60)
)

# Чи вважати запит БЕЗ будь-якої автентифікації «локальним користувачем».
#
# Так проєкт жив, поки був однокористувацьким, і для розробки це зручно:
# відкрив http://127.0.0.1:8000 і одразу працюєш. Але на сервері це
# означає «хто дістався до порту — той і господар», тож за замовчуванням
# режим ВИМКНЕНО, і вмикати його треба свідомо, у своєму .env.
ALLOW_LOCAL_USER = os.environ.get("ALLOW_LOCAL_USER", "").lower() in {
    "1",
    "true",
    "yes",
}

# HTTPS-деплой вмикає Secure; для локального HTTP лишається вимкнено.
SESSION_COOKIE_SECURE = os.environ.get("SESSION_COOKIE_SECURE", "").lower() in {
    "1",
    "true",
    "yes",
}

# Порожнє значення вимикає періодичні копії. Compose задає /data/backups.
BACKUP_DIR = os.environ.get("BACKUP_DIR", "")
