"""Українське відмінювання числівників.

Винесено окремо, бо потрібне вже двом модулям: нагадування рахують
звички, картка звички — дні. Правило одне, тож і код має бути один.
"""


def plural(count: int, one: str, few: str, many: str) -> str:
    """Обрати форму слова за числом.

        plural(1, "день", "дні", "днів")   -> "день"
        plural(3, "день", "дні", "днів")   -> "дні"
        plural(5, "день", "дні", "днів")   -> "днів"

    Правило дивиться на ОСТАННЮ цифру, але з винятком на числа 11-14:
    вони завжди беруть форму many, хоч і закінчуються на 1-4. Тобто
    «21 день», але «11 днів»; «22 дні», але «12 днів». Без цього
    винятку виходило б «11 день» — помилка, яку чути одразу.
    """
    if count % 10 == 1 and count % 100 != 11:
        return one
    if 2 <= count % 10 <= 4 and not (12 <= count % 100 <= 14):
        return few
    return many
